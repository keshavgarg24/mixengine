"""
The vocal layers that make a take sound produced.

A lead vocal alone over a beat reads as a demo however well it is mixed.
What a record adds is layers: doubles that thicken the hook, an octave
underneath, a harmony on the last line, ad-libs answering in the gaps. The
engine can generate all of these from the single take it has, and this is
where the biggest audible difference between "a mix" and "a song" lives.

The thing that makes a synthetic double work -- or fail completely -- is
that **it must differ in time and pitch, and differ continuously**. A
delayed copy of a signal is not a double, it is a comb filter: every
frequency whose period divides the delay cancels, and the result is a
hollow, phasey lead rather than a thicker one. A real double is a second
performance, so it drifts a few tens of milliseconds around the lead and
sits a few cents off it, and both wander across the phrase.

So doubles here are generated by warping the lead along a slow random walk
and detuning it slightly, reusing the same variable-rate machinery the
alignment stage uses. The walk is seeded per layer, which keeps renders
reproducible -- an unreproducible mix cannot be debugged.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from typing import Callable, Dict, List, Optional, Sequence, Tuple

import numpy as np

from ..align import warp as warp_mod
from ..audio import dsp

log = logging.getLogger("mixengine.arrange.layers")

# Timing and tuning spread for a generated double, in ms and cents. These
# are the measured range of real double-tracking, not free parameters: much
# less and the comb filtering returns, much more and it reads as two
# different singers rather than one singer twice.
DOUBLE_TIME_SPREAD_MS = 22.0
DOUBLE_DETUNE_CENTS = 11.0
WIDE_TIME_SPREAD_MS = 34.0
WIDE_DETUNE_CENTS = 16.0

# How often the walk changes direction. Around a second: fast enough to be
# a performance, slow enough not to be vibrato.
WALK_PERIOD_S = 0.9


@dataclass
class Layer:
    name: str
    audio: np.ndarray
    gain_db: float = -8.0
    pan: float = 0.0
    regions: List[Tuple[int, int]] = field(default_factory=list)
    note: str = ""

    def to_dict(self) -> dict:
        return {"name": self.name, "gain_db": round(self.gain_db, 2),
                "pan": round(self.pan, 3), "regions": len(self.regions),
                "note": self.note}


def build(vocal: np.ndarray, sr: int, *,
          wanted: Dict[str, List[Tuple[int, int]]],
          tessitura: Optional[Tuple[float, float]] = None,
          seed: int = 0,
          notes: Optional[Sequence] = None,
          chord_at: Optional[Callable[[float], object]] = None,
          key_at: Optional[Callable[[float], object]] = None
          ) -> Tuple[List[Layer], dict]:
    """Generate every requested layer over the regions it applies to.

    `wanted` maps a layer name to the sample regions it should cover, which
    the arranger derives from the energy contour: doubles on hooks, harmony
    only where the energy is highest, ad-libs in the gaps. A layer with no
    regions is not generated at all rather than generated and muted, since
    the generation is the expensive part.

    `notes`, `chord_at` and `key_at` make the harmony chord-aware. Without
    them it falls back to a diatonic third and says so in its note.
    """
    v = dsp.as_2d(vocal)
    out: List[Layer] = []
    report: Dict = {"requested": sorted(wanted.keys()), "built": [],
                    "skipped": {}}

    builders = {
        "tight_double": lambda r: _double(
            v, sr, r, DOUBLE_TIME_SPREAD_MS, DOUBLE_DETUNE_CENTS,
            gain_db=-9.0, pan=0.0, seed=seed + 1, name="tight_double"),
        "wide_double": lambda r: _wide_pair(
            v, sr, r, seed=seed + 2),
        "octave_down": lambda r: _octave(v, sr, r, -12.0, gain_db=-16.0,
                                         seed=seed + 4),
        "harmony": lambda r: _harmony(v, sr, r, tessitura, seed=seed + 5,
                                      notes=notes, chord_at=chord_at,
                                      key_at=key_at),
        "adlibs": lambda r: _adlibs(v, sr, r, seed=seed + 6),
        "whisper_layer": lambda r: _whisper(v, sr, r, seed=seed + 7),
    }

    for name, regions in wanted.items():
        fn = builders.get(name)
        if fn is None:
            report["skipped"][name] = "no builder"
            continue
        if not regions:
            report["skipped"][name] = "no regions"
            continue
        try:
            made = fn(regions)
        except Exception as exc:
            log.warning("layer %s failed: %s", name, exc)
            report["skipped"][name] = f"failed: {exc}"
            continue
        for layer in (made if isinstance(made, list) else [made]):
            if layer is None:
                continue
            out.append(layer)
            report["built"].append(layer.to_dict())
    return out, report


